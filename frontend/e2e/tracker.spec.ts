import { expect, test } from '@playwright/test'
import { fillReviewDates } from './create-board'

test('sign in, create a board, edit notes, and filter the board list', async ({ page }) => {
  test.skip(!process.env.E2E_DEV_PASSWORD, 'Set E2E_DEV_PASSWORD against a dedicated development instance')
  const identifier = 'SRC' + String(Date.now() % 100000).padStart(5, '0')
  await page.goto('/')
  await page.getByLabel('Username').fill('demo.admin')
  await page.getByLabel('Password').fill(process.env.E2E_DEV_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Engineering dashboard' })).toBeVisible()
  await page.getByRole('link', { name: 'New board' }).click()
  await page.getByRole('dialog').getByRole('textbox', {name:'Board identifier *',exact:true}).fill(identifier)
  await page.getByRole('combobox', { name: 'Schematic RI' }).selectOption({ label: 'Demo Admin · demo.admin' })
  await page.getByRole('button', { name: 'Create board' }).click()
  await expect(page.getByText('Enter a review date.', {exact:true})).toHaveCount(5)
  await fillReviewDates(page)
  await page.getByRole('group', {name:'Functional Overview Review'}).getByLabel('Review hyperlink').fill('https://example.test/review')
  await page.getByRole('button', { name: 'Create board' }).click()
  await expect(page.getByRole('heading', { name: identifier })).toBeVisible()
  const timeline = page.getByRole('region', {name:'Review dates by month'})
  await expect(timeline.getByText('Today', {exact:true})).toBeVisible()
  await expect(timeline.locator('.review-milestone')).toHaveCount(5)
  const positions = await timeline.locator('.review-milestone').evaluateAll(markers=>markers.map(marker=>({
    left: (marker as HTMLElement).style.left, top: marker.getBoundingClientRect().top,
  })))
  expect(new Set(positions.map(marker=>marker.left)).size).toBe(1)
  expect(new Set(positions.map(marker=>marker.top)).size).toBe(5)
  const review = page.locator('section.record-section').filter({
    has:page.getByRole('heading', {name:'Functional Overview Review', exact:true}),
  }).last()
  const link = review.getByRole('link', {name:'Open link'})
  await expect(link).toHaveAttribute('href','https://example.test/review')
  await expect(link).toHaveAttribute('target','_blank')
  await review.getByRole('button', {name:'Edit'}).click()
  await review.getByLabel('Review date').fill('2027-06-01')
  await review.getByLabel('State').selectOption('Working Action Items')
  await review.getByLabel('Review hyperlink').fill('https://example.test/updated-review')
  await review.getByRole('button', {name:'Save changes'}).click()
  await expect(timeline.getByText('Jun 1, 2027 · Working Action Items',{exact:true})).toBeVisible()
  await expect(link).toHaveAttribute('href','https://example.test/updated-review')
  const history = page.locator('details.collapsible').filter({hasText:'Activity history'})
  await expect(history).not.toHaveAttribute('open','')
  await history.locator(':scope > summary').click()
  const log = history.getByRole('region',{name:'Activity log'})
  await expect(log).toBeVisible()
  expect(await log.evaluate(node=>getComputedStyle(node).maxHeight)).toBe('400px')
  expect(await log.evaluate(node=>node.scrollHeight>node.clientHeight)).toBe(true)
  await history.locator(':scope > summary').click()
  await expect(log).toBeHidden()
  const overview = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Overview', exact: true }) })
  await overview.getByRole('button', { name: 'Edit' }).click()
  await overview.getByLabel('Notes').fill('Playwright verification notes')
  await overview.getByRole('button', { name: 'Save changes' }).click()
  await expect(overview.getByText('Playwright verification notes')).toBeVisible()
  await page.getByRole('link', { name: 'Boards', exact: true }).last().click()
  await page.getByRole('textbox', { name: 'Board identifier search' }).fill(identifier)
  await expect(page.getByRole('link', { name: identifier })).toBeVisible()
  await expect(page).toHaveURL(new RegExp('q='+identifier))
})


test('defaults to dark and retains the chosen light theme', async ({page})=>{
  test.skip(!process.env.E2E_DEV_PASSWORD, 'Set E2E_DEV_PASSWORD against a dedicated development instance')
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.getByLabel('Username').fill('demo.admin')
  await page.getByLabel('Password').fill(process.env.E2E_DEV_PASSWORD!)
  await page.getByRole('button',{name:'Sign in'}).click()
  await page.getByRole('button',{name:'Toggle theme'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme','light')
})
