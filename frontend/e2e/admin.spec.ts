import { expect, test } from '@playwright/test'

test('create a program, associate a board, manage reviews, and restore a deleted record', async ({ page }) => {
  test.skip(!process.env.E2E_DEV_PASSWORD, 'Set E2E_DEV_PASSWORD against a dedicated development instance')
  const tag = String(Date.now() % 100000).padStart(5, '0')
  const identifier = 'SRC'+tag+'B'
  const program = 'E2E Synthetic '+tag
  await page.goto('/programs')
  await page.getByLabel('Username').fill('demo.admin')
  await page.getByLabel('Password').fill(process.env.E2E_DEV_PASSWORD!)
  await page.getByRole('button', {name:'Sign in'}).click()
  await page.getByRole('button', {name:'New program'}).click()
  await page.getByRole('textbox', {name:'Name *',exact:true}).fill(program)
  await page.getByRole('button', {name:'Create record'}).click()
  await expect(page.getByRole('heading', {name:program})).toBeVisible()
  await page.getByRole('link', {name:'Boards', exact:true}).first().click()
  await page.getByRole('button', {name:'New board'}).click()
  await page.getByRole('dialog').getByRole('textbox', {name:'Board identifier *',exact:true}).fill(identifier)
  await page.getByRole('combobox', {name:'Schematic RI'}).selectOption({label:'Demo Admin · demo.admin'})
  await page.getByRole('button', {name:'Show optional fields'}).click()
  const programs = page.getByRole('dialog').locator('.form-field').filter({hasText:/^Programs/})
  await programs.getByRole('button', {name:'Select people or records'}).click()
  await programs.getByRole('checkbox', {name:program}).check()
  await page.getByRole('button', {name:'Create record'}).click()
  await expect(page.getByRole('heading', {name:identifier})).toBeVisible()
  await expect(page.getByRole('link', {name:program})).toBeVisible()
  const verification = page.locator('section.record-section').filter({has:page.getByRole('heading', {name:'Board Verification (Unit Test)',exact:true})}).last()
  await verification.getByRole('button', {name:'Edit'}).click()
  await verification.getByLabel('State').selectOption('Complete')
  await verification.getByRole('button', {name:'Save changes'}).click()
  await expect(verification.getByText('Complete')).toBeVisible()
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', {name:'Delete board'}).click()
  await expect(page.getByRole('button', {name:'Restore board'})).toBeVisible()
  await page.getByRole('button', {name:'Restore board'}).click()
  await expect(page.getByRole('button', {name:'Delete board'})).toBeVisible()
})
